def _rule_row_html(rule_id: str, rule: dict) -> str:
    status = rule.get("status", "UNABLE")
    tone = {"PASS": "ok", "FAIL": "bad", "UNABLE": "warn"}.get(status, "warn")
    return f"""
<div class="rule-row tone-{tone}">
  <span class="rule-id">{_esc(rule_id)}</span>
  <span class="status-pill tone-{tone}">{_esc(status)}</span>
  <span class="rule-message">{_esc(rule.get('message'))}</span>
</div>"""


def _record_section_html(record: dict) -> str:
    verdict = record.get("verdict", "REVIEW")
    verdict_tone = {"VALID": "ok", "REVIEW": "warn", "INVALID": "bad"}.get(verdict, "warn")
    ocr = record.get("ocr_verifications") or {}
    rules = record.get("rules") or {}

    ocr_disagreements = sum(1 for fv in ocr.values()
                            if fv.get("comparison", {}).get("status") == "DISAGREE")
    not_secondarily_verified = sum(
        1 for fv in ocr.values()
        if fv.get("comparison", {}).get("status") in
        ("DI_ONLY", "CROP_REJECTED", "TROCR_NOT_RUN", "TROCR_FAILED"))
    manual_review_fields = sum(
        1 for fv in ocr.values()
        if fv.get("comparison", {}).get("manual_review_required"))

    field_cards = "".join(_field_card_html(name, fv) for name, fv in ocr.items())
    rule_rows = "".join(_rule_row_html(rid, r) for rid, r in rules.items())

    ocr_block = (field_cards if field_cards else
                '<div class="empty-note">TrOCR verification was not run for this '
                'record (feature disabled, or the cheque predates this feature).</div>')

    return f"""
<section class="record-card tone-{verdict_tone}" id="record-{_esc(record.get('record_id'))}">
  <div class="record-head">
    <div>
      <span class="record-id">{_esc(record.get('record_id'))}</span>
      <span class="source-file">{_esc(record.get('source_file'))}</span>
    </div>
    <div class="record-head-right">
      <span class="status-pill tone-{verdict_tone}">{_esc(verdict)}</span>
      <span class="manual-review-flag">{'Manual review required' if manual_review_fields or verdict != 'VALID' else 'No additional OCR review flags'}</span>
    </div>
  </div>
  <div class="record-meta">
    Processed {_esc(record.get('processed_time'))} &middot;
    Ruleset {_esc(record.get('ruleset_version'))} &middot;
    OCR disagreements: {ocr_disagreements} &middot;
    Fields not secondarily verified: {not_secondarily_verified}
  </div>
  <h4 class="section-heading">Field verification (Document Intelligence vs. TrOCR)</h4>
  <div class="field-cards">{ocr_block}</div>
  <h4 class="section-heading">Deterministic business rules (unchanged, all still executed)</h4>
  <div class="rule-rows">{rule_rows}</div>
</section>"""


def generate_verification_html(records: list[dict], reviews: list[dict] | None = None,
                               *, trocr_model_id: str = TROCR_DEFAULT_MODEL_ID,
                               trocr_model_revision: str | None = None,
                               di_model_id: str = _report.MODEL_ID) -> str:
    reviews = reviews or []
    total = len(records)
    verified_records = [r for r in records if r.get("ocr_verifications")]
    total_disagreements = sum(
        1 for r in records for fv in (r.get("ocr_verifications") or {}).values()
        if fv.get("comparison", {}).get("status") == "DISAGREE")
    total_not_verified_fields = sum(
        1 for r in records for fv in (r.get("ocr_verifications") or {}).values()
        if fv.get("comparison", {}).get("status") in
        ("DI_ONLY", "CROP_REJECTED", "TROCR_NOT_RUN", "TROCR_FAILED"))
    rule_failures = sum(1 for r in records for rule in (r.get("rules") or {}).values()
                        if rule.get("status") == "FAIL")
    rule_undetermined = sum(1 for r in records for rule in (r.get("rules") or {}).values()
                            if rule.get("status") == "UNABLE")
    manual_review_needed = sum(1 for r in records if r.get("verdict") != "VALID") or \
        sum(1 for r in records for fv in (r.get("ocr_verifications") or {}).values()
           if fv.get("comparison", {}).get("manual_review_required"))

    generated = datetime.now().astimezone().isoformat(timespec="seconds")
    records_sorted = sorted(records, key=lambda r: r.get("processed_time", ""), reverse=True)
    record_sections = "".join(_record_section_html(r) for r in records_sorted)

    return _TEMPLATE.format(
        css=_CSS,
        generated=html.escape(generated),
        total=total,
        verified_count=len(verified_records),
        report_schema_version=VERIFICATION_SCHEMA_VERSION,
        ruleset_version=html.escape(RULE_SET_VERSION),
        di_model_id=html.escape(di_model_id),
        trocr_model_id=html.escape(trocr_model_id),
        trocr_model_revision=html.escape(trocr_model_revision or "unpinned"),
        reviewer_notice=html.escape(REVIEWER_NOTICE),
        rule_failures=rule_failures,
        rule_undetermined=rule_undetermined,
        total_disagreements=total_disagreements,
        total_not_verified_fields=total_not_verified_fields,
        manual_review_needed=manual_review_needed,
        record_sections=record_sections or
        '<div class="empty-note">No cheque records yet.</div>',
    )


def regenerate_verification_report(*, trocr_model_id: str = TROCR_DEFAULT_MODEL_ID,
                                   trocr_model_revision: str | None = None) -> Path:
    """Rebuild the verification report in full from the current JSON records -
    same "always fully rebuilt, never patched" policy as report.py's own
    regenerate_report(). Safe to call even when no record has ocr_verifications
    data yet (renders an honest "not run" state per record instead of
    erroring)."""
    records = _report.load_records()
    reviews = _report.load_reviews()
    html_text = generate_verification_html(
        records, reviews, trocr_model_id=trocr_model_id,
        trocr_model_revision=trocr_model_revision)
    _report._atomic_write_text(HTML_VERIFICATION_REPORT, html_text)
    return HTML_VERIFICATION_REPORT


