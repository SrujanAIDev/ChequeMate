"""ChequeMate AI Review and OCR Verification Report - a SEPARATE, additive
report version. The original reports/chequemate_report.html is never
touched by this module (still generated by report.regenerate_report(),
unchanged) - this writes a second file,
reports/chequemate_verification_report.html, so the original stays
available for rollback/comparison at all times, per the task's explicit
"create a new report version, do not silently change the current one"
requirement.

Reuses report.py's JSON-embedding helper (`_json_for_script`) and data
access functions (`load_records`, `load_reviews`) rather than duplicating
them - this module owns only what's genuinely new: the verification-
specific template and the summary/field-verification rendering logic.

Every record already stored in cheques.json (via report.create_report_record)
is privacy-safe by construction - no MICR, no account numbers, no signature
images, no raw Azure response ever gets persisted there (see report.py's
"privacy boundary" design). This report renders directly from that same
already-safe data plus the new `ocr_verifications` field, so it inherits
those guarantees rather than needing to re-implement them.
"""

